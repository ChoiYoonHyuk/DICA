"""Generate a runnable corrected copy using SHA-guarded exact transformations.

This build tool requires only the Python standard library. Original source is
never edited; generated runner retains all original CLI arguments and methods.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ORIGINAL_SHA256 = "989006c397c99d766edfd64f241d9d85347ba920a43d28c535f9668987d853af"
VERSION = "rea-v3-audit-corrected"


def replace_line(source, old, replacement, count=1):
    lines = source.splitlines(keepends=True)
    matches = [i for i, line in enumerate(lines) if line.strip() == old]
    if len(matches) != count:
        raise RuntimeError(f"Expected {count} occurrence(s) of {old!r}, got {len(matches)}")
    for i in reversed(matches):
        indent = lines[i][:len(lines[i])-len(lines[i].lstrip())]
        lines[i] = "".join(indent + line + "\n" for line in replacement.splitlines())
    return "".join(lines)


def patch_suffix_source(source):
    old = "lin=linear_box_tight if tight else linear_box"
    replacement = (
        "point = exact_suffix_point_box(self, attention_box, h, per_layer_input, operator_trace)\n"
        "if point is not None:\n"
        "    return point\n" + old)
    source = replace_line(source, old, replacement)
    old = "return record(name,rms(box,weight,eps,self.dtype))"
    replacement = (
        "if self.family == 'gemma4':\n"
        "    return record(name, rms_box_corrected(box, weight, eps, self.dtype, scale_before_cast=True))\n"
        + old)
    return replace_line(source, old, replacement)


def patch_score_source(source, expected=1):
    forms = ("score_error = gamma(self.d+4,torch.float32)*max_score",
             "score_error=gamma(self.d+4,torch.float32)*max_score")
    total = sum(sum(line.strip() == form for line in source.splitlines()) for form in forms)
    if total != expected:
        raise RuntimeError(f"Expected {expected} score allowance(s), found {total}")
    for form in forms:
        count = sum(line.strip() == form for line in source.splitlines())
        if count:
            source = replace_line(source, form,
                "score_error = attention_score_roundoff(q, root.kmin[g], root.kmax[g])", count)
    return source


def build(source_path: Path, output_path: Path):
    raw = source_path.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != ORIGINAL_SHA256:
        raise RuntimeError(f"Original SHA256 mismatch: expected {ORIGINAL_SHA256}, got {digest}")
    if source_path.resolve() == output_path.resolve():
        raise RuntimeError("Output must not overwrite the original runner")
    source = raw.decode("utf-8-sig").replace("\r\n", "\n")
    source = patch_suffix_source(source)
    source = patch_score_source(source, expected=2)
    source = replace_line(source,
        'ids=tok.apply_chat_template([{"role":"user","content":text}],tokenize=True,add_generation_prompt=True)',
        'ids=chat_token_ids(tok,text)')
    source = replace_line(source, 'IMPLEMENTATION_VERSION = "rea-v2.1-qwen-gemma4-cachefix3"',
                          f'IMPLEMENTATION_VERSION = "{VERSION}"')
    source = replace_line(source, 'LOG = logging.getLogger("rea")',
        "from bound_fixes import exact_suffix_point_box, rms_box_corrected, attention_score_roundoff\n\n"
        "from tokenizer_compat import chat_token_ids\n"
        'LOG = logging.getLogger("rea")')
    header = ("# Generated by build_corrected_runner.py; original source remains unchanged.\n"
              f"# Source SHA256: {digest}\n"
              "# Correctness repairs only; this file makes no speedup claim.\n")
    source = header + source
    compile(source, str(output_path), "exec")
    output_path.write_text(source, encoding="utf-8", newline="\n")
    manifest = {"source": source_path.name, "source_sha256": digest,
                "output": output_path.name, "output_sha256": hashlib.sha256(output_path.read_bytes()).hexdigest(),
                "version": VERSION,
                "changes": ["Gemma4 FP32-scale-before-output-cast semantics", "native singleton suffix",
                            "absolute-product score allowance in both frontiers",
                            "explicit non-dictionary chat-template token IDs"],
                "original_modified": False, "automatic_dense_gate": False,
                "required_companion_files": ["bound_fixes.py", "original_runner.py", "tokenizer_compat.py"]}
    output_path.with_suffix(".provenance.json").write_text(json.dumps(manifest, indent=2)+"\n", encoding="utf-8")
    return manifest


def main():
    root = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=root / "original_runner.py")
    parser.add_argument("--output", type=Path, default=root / "corrected_runner.py")
    args = parser.parse_args()
    print(json.dumps(build(args.source, args.output), indent=2))


if __name__ == "__main__":
    main()
